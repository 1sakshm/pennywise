"""Write every number, table and figure the report uses, from eval outputs only.

Reads eval/results/{all,sft_history,rl_lam*}.json + web/public/data/{umap,training/*}.json
(+ config/*.yaml for setup facts). Writes <out>/generated/*.typ and <out>/figures/*.
<out> = paper/ normally; data/cache/synthetic/paper/ when SYNTHETIC=1 (never committed).
Never hand-edit generated/*.typ.
"""
import glob
import json
import shutil
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import yaml  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from router.paths import RESULTS, SYNTHETIC, VIZ  # noqa: E402

OUT = ROOT / "data" / "cache" / "synthetic" / "paper" if SYNTHETIC else ROOT / "paper"
GEN, FIG = OUT / "generated", OUT / "figures"
TIER_C = {"small": "#14b8a6", "medium": "#6366f1", "large": "#db2777"}
SRC = {"math": "MATH L4-5", "mmlu_pro": "MMLU-Pro", "gsm8k": "GSM8K", "arc": "ARC-Challenge", "mbpp": "MBPP", "alan_bugfix": "Agent bug-fix", "alan_triage": "Agent CI triage"}


def p1(x):
    return f"{100 * x:.1f}"


def esc(s):
    return str(s).replace("\\", "\\\\").replace('"', '\\"')


def label(r):
    return r["name"] + (f" (λ={r['lambda']:g})" if r.get("lambda") is not None else "")


def numbers(allr, cfg_train, cfg_models, sft):
    P = allr["policies"]
    get = lambda n, lam=None: next(p for p in P if p["name"] == n and p.get("lambda") == lam)  # noqa: E731
    m = allr["modes"]
    auto, large, zs = get("RL Laya", m["auto"]), get("always-large"), get("zero-shot Laya")
    prompts = [json.loads(l) for l in open(ROOT / "data" / "processed" / "prompts.jsonl", encoding="utf-8")]
    n = {s: sum(1 for r in prompts if r["split"] == s) for s in ("train", "val", "test")}
    L = [f"// GENERATED by paper/gen_tables.py from eval/results — do not edit",
         f"#let synthetic = {str(allr['synthetic']).lower()}",
         f'#let n_prompts = {len(prompts)}', f'#let n_train = {n["train"]}', f'#let n_val = {n["val"]}', f'#let n_test = {allr["n_test"]}',
         f'#let n_boot = {allr["bootstrap"]}', f'#let seed = {allr["seed"]}',
         f'#let lam_auto = "{m["auto"]:g}"', f'#let lam_quality = "{m["auto-quality"]:g}"', f'#let lam_cheap = "{m["auto-cheap"]:g}"',
         f'#let auto_acc = "{p1(auto["accuracy"])}"', f'#let auto_acc_lo = "{p1(auto["accuracy_ci"][0])}"', f'#let auto_acc_hi = "{p1(auto["accuracy_ci"][1])}"',
         f'#let auto_cost = "{p1(auto["cost_vs_large"])}"', f'#let auto_cost_lo = "{p1(auto["cost_vs_large_ci"][0])}"', f'#let auto_cost_hi = "{p1(auto["cost_vs_large_ci"][1])}"',
         f'#let auto_vs_large = "{100 * auto["vs_always_large_acc"]["diff"]:+.1f}"',
         f'#let auto_vs_large_lo = "{100 * auto["vs_always_large_acc"]["ci"][0]:+.1f}"', f'#let auto_vs_large_hi = "{100 * auto["vs_always_large_acc"]["ci"][1]:+.1f}"',
         f'#let large_acc = "{p1(large["accuracy"])}"', f'#let zs_acc = "{p1(zs["accuracy"])}"', f'#let zs_cost = "{p1(zs["cost_vs_large"])}"',
         f'#let router_ms = "{auto["router_latency_ms"]:.1f}"' if auto["router_latency_ms"] is not None else '#let router_ms = "n/a"',
         f'#let cost_ref = "{allr["cost_ref_usd"]:.6f}"', f'#let jev_status = "{esc(allr["jev"])}"',
         f'#let sft_zs_val = "{p1(sft["zero_shot"]["val_acc_vs_oracle"])}"', f'#let sft_best_val = "{p1(sft["best"]["val_acc_vs_oracle"])}"',
         f'#let sft_best_epoch = {sft["best"]["epoch"]}']
    rl = cfg_train["rl"]
    L += [f'#let rl_steps = {rl["steps"]}', f'#let rl_batch = {rl["batch_size"]}', f'#let rl_lr = "{rl["lr"]:g}"',
          f'#let beta_start = "{rl["entropy_beta_start"]:g}"', f'#let beta_end = "{rl["entropy_beta_end"]:g}"',
          f'#let lambdas = "{", ".join(f"{x:g}" for x in rl["lambdas"])}"', f'#let n_top = {cfg_train["sft"]["train_encoder_layers"]}',
          f'#let sft_lr = "{cfg_train["sft"]["lr"]:g}"', f'#let sft_epochs = {cfg_train["sft"]["epochs"]}']
    tiers = cfg_models["tiers"]
    rows = ", ".join(f'("{t}", "{esc(tiers[t]["model"])}", "{tiers[t]["price_in_per_m"]}", "{tiers[t]["price_out_per_m"]}")' for t in ("small", "medium", "large"))
    L.append(f"#let tier_rows = ({rows},)")
    (GEN / "numbers.typ").write_text("\n".join(L) + "\n", encoding="utf-8")


def results_table(allr):
    P = [p for p in allr["policies"] if not (p["kind"] == "correctness-predictor" and p["lambda"] not in (0.1, 0.25, 0.5, 1.0))]
    cells = []
    for r in P:
        ms = "" if r["router_latency_ms"] is None else f"{r['router_latency_ms']:.1f}"
        cells.append(f'[{esc(label(r))}], [{p1(r["accuracy"])} [{p1(r["accuracy_ci"][0])}, {p1(r["accuracy_ci"][1])}]], '
                     f'[{p1(r["cost_vs_large"])} [{p1(r["cost_vs_large_ci"][0])}, {p1(r["cost_vs_large_ci"][1])}]], [{ms}], '
                     f'[{"✓" if r.get("on_pareto_front") else ""}]')
    body = ",\n  ".join(cells)
    (GEN / "results_table.typ").write_text(
        "// GENERATED — do not edit\n#table(columns: (auto, auto, auto, auto, auto), align: (left, right, right, right, center),\n"
        "  stroke: none, table.hline(),\n  [*Policy*], [*Accuracy % [95% CI]*], [*Cost % of always-large [95% CI]*], [*Router ms*], [*Pareto*],\n"
        f"  table.hline(stroke: 0.5pt),\n  {body},\n  table.hline())\n", encoding="utf-8")


def source_table(allr):
    P = allr["policies"]
    get = lambda n, lam=None: next(p for p in P if p["name"] == n and p.get("lambda") == lam)  # noqa: E731
    pols = [get("always-small"), get("always-medium"), get("always-large"), get("RL Laya", allr["modes"]["auto"])]
    srcs = list(pols[0]["by_source"])
    head = ", ".join(f"[*{esc(label(p))}*]" for p in pols)
    rows = []
    for s in srcs:
        n = pols[0]["by_source"][s]["n"]
        cells = ", ".join(f'[{p1(p["by_source"][s]["accuracy"])} / {p1(p["by_source"][s]["cost_vs_large"])}]' for p in pols)
        rows.append(f"[{SRC.get(s, s)} (n={n})], {cells}")
    (GEN / "source_table.typ").write_text(
        f"// GENERATED — do not edit. Cells: accuracy % / cost % of always-large.\n#table(columns: {len(pols) + 1}, stroke: none, align: (left,) + (right,) * {len(pols)},\n"
        f"  table.hline(), [*Source*], {head}, table.hline(stroke: 0.5pt),\n  " + ",\n  ".join(rows) + ",\n  table.hline())\n", encoding="utf-8")


def fig_pareto(allr):
    P = allr["policies"]
    fig, ax = plt.subplots(figsize=(6.4, 4.2))
    rl = sorted([p for p in P if p["kind"] == "rl"], key=lambda p: p["cost_vs_large"])
    for emb, ls in (("Laya-emb", "--"), ("MiniLM-emb", ":")):
        c = sorted([p for p in P if p["kind"] == "correctness-predictor" and emb in p["name"]], key=lambda p: p["cost_vs_large"])
        ax.plot([p["cost_vs_large"] for p in c], [p["accuracy"] for p in c], ls, color="#64748b", label=f"per-tier LR ({emb})")
    x = [p["cost_vs_large"] for p in rl]
    ax.fill_between(x, [p["accuracy_ci"][0] for p in rl], [p["accuracy_ci"][1] for p in rl], color="#eab308", alpha=0.2)
    ax.plot(x, [p["accuracy"] for p in rl], "-o", color="#ca8a04", label="RL-trained Laya (λ sweep)", ms=4)
    for p in P:
        if p["kind"] in ("trivial", "oracle", "laya", "embedding") and p["name"] != "random":
            col = TIER_C.get(p["name"].replace("always-", ""), "#334155")
            ax.errorbar(p["cost_vs_large"], p["accuracy"], yerr=[[p["accuracy"] - p["accuracy_ci"][0]], [p["accuracy_ci"][1] - p["accuracy"]]],
                        fmt="o" if p["kind"] != "oracle" else "D", color=col, ms=5, capsize=2, mfc="none" if p["kind"] == "oracle" else col)
            ax.annotate(p["name"], (p["cost_vs_large"], p["accuracy"]), fontsize=7, xytext=(4, 3), textcoords="offset points")
    ax.set_xlabel("cost relative to always-large")
    ax.set_ylabel("accuracy (test)")
    ax.grid(alpha=0.25)
    ax.legend(fontsize=7, loc="lower right")
    fig.tight_layout()
    fig.savefig(FIG / "pareto.pdf")
    fig.savefig(FIG / "pareto.png", dpi=180)  # README (GitHub does not render PDF images)
    plt.close(fig)


def fig_reward_curves():
    fig, ax = plt.subplots(figsize=(6.4, 3.4))
    for f in sorted(glob.glob(str(RESULTS / "rl_lam*.json")), key=lambda f: json.load(open(f))["lambda"]):
        r = json.load(open(f))
        rew = np.array([h["reward"] for h in r["train_curve"]])
        k = 25
        ma = np.convolve(rew, np.ones(k) / k, mode="valid")
        ax.plot(np.arange(len(ma)) + k, ma, label=f"λ={r['lambda']:g}", lw=1.3)
    ax.set_xlabel("RL step")
    ax.set_ylabel("train reward (25-step moving avg.)")
    ax.grid(alpha=0.25)
    ax.legend(fontsize=7, ncol=3)
    fig.tight_layout()
    fig.savefig(FIG / "reward_curves.pdf")
    plt.close(fig)


def fig_brainmaps(lam):
    um = json.load(open(VIZ / "umap.json"))
    tr = json.load(open(VIZ / "training" / f"{lam:g}.json"))["checkpoints"]
    xy = np.array(um["xy"])
    picks = [("early", tr[0]), ("mid", tr[len(tr) // 2]), ("final", tr[-1])]
    cols = np.array([TIER_C["small"], TIER_C["medium"], TIER_C["large"]])
    for name, ck in picks:
        fig, ax = plt.subplots(figsize=(3.4, 3.4))
        ax.scatter(xy[:, 0], xy[:, 1], s=2 + 14 * np.array(ck["prob"]), c=cols[np.array(ck["action"])], alpha=0.75, lw=0)
        ax.set_title(f"step {ck['step']}", fontsize=9)
        ax.set_xticks([])
        ax.set_yticks([])
        for s in ax.spines.values():
            s.set_visible(False)
        fig.tight_layout()
        fig.savefig(FIG / f"brainmap_{name}.png", dpi=220)
        plt.close(fig)


def main():
    GEN.mkdir(parents=True, exist_ok=True)
    FIG.mkdir(parents=True, exist_ok=True)
    allr = json.load(open(RESULTS / "all.json"))
    sft = json.load(open(RESULTS / "sft_history.json"))
    cfg_train = yaml.safe_load(open(ROOT / "config" / "train.yaml"))
    cfg_models = yaml.safe_load(open(ROOT / ("tests/models.mock.yaml" if SYNTHETIC else "config/models.yaml")))
    numbers(allr, cfg_train, cfg_models, sft)
    results_table(allr)
    source_table(allr)
    fig_pareto(allr)
    fig_reward_curves()
    fig_brainmaps(allr["modes"]["auto"])
    if SYNTHETIC:  # compile a throwaway copy, never touching paper/generated
        for f in ("main.typ", "refs.bib"):
            if (ROOT / "paper" / f).exists():
                shutil.copy(ROOT / "paper" / f, OUT / f)
    print(f"{'SYNTHETIC ' if SYNTHETIC else ''}generated tables/figures -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
